package app.lightscout.storage;

import java.security.GeneralSecurityException;

/**
 * Seam over the ST-06 token key so that the {@link KeystoreConnectionStore} rules are JVM-testable; the only
 * production implementation is {@link KeystoreTokenCipher} (Android Keystore AES-256-GCM, SR-01).
 */
interface TokenCipher {

    /**
     * Encrypts with a fresh IV chosen by the key provider (never by the caller, SR-01 / SR-08). Creates the key
     * when it does not exist.
     *
     * @param plaintext UTF-8 token bytes; not retained
     * @return IV and ciphertext (incl. the 128-bit tag)
     * @throws GeneralSecurityException on any key or cipher failure
     */
    SealedToken encrypt(byte[] plaintext) throws GeneralSecurityException;

    /**
     * Decrypts a sealed token.
     *
     * @param sealed IV and ciphertext
     * @return plaintext bytes; the caller wipes them
     * @throws GeneralSecurityException when the key is missing, invalidated or the data does not authenticate
     */
    byte[] decrypt(SealedToken sealed) throws GeneralSecurityException;

    /**
     * Deletes the key (no-op when it does not exist).
     *
     * @throws GeneralSecurityException on a key store failure
     */
    void deleteKey() throws GeneralSecurityException;

    /**
     * IV and ciphertext of one encryption.
     *
     * @param iv         GCM IV generated by the key provider
     * @param ciphertext ciphertext with the GCM tag
     */
    record SealedToken(byte[] iv, byte[] ciphertext) {
    }
}
